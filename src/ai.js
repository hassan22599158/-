function getPieceValue(piece, x, y) {
    if (piece === null) {
        return 0;
    }

    const getAbsoluteValue = function (piece, isWhite, x ,y) {
        if (piece.type === 'p') {
            return 10 + ( isWhite ? pawnEvalWhite[y][x] : pawnEvalBlack[y][x] );
        } else if (piece.type === 'r') {
            return 50 + ( isWhite ? rookEvalWhite[y][x] : rookEvalBlack[y][x] );
        } else if (piece.type === 'n') {
            return 32 + knightEval[y][x];
        } else if (piece.type === 'b') {
            return 33 + ( isWhite ? bishopEvalWhite[y][x] : bishopEvalBlack[y][x] );
        } else if (piece.type === 'q') {
            return 90 + evalQueen[y][x];
        } else if (piece.type === 'k') {
            return 900 + ( isWhite ? kingEvalWhite[y][x] : kingEvalBlack[y][x] );
        }
        throw "Unknown piece type: " + piece.type;
    };

    const absoluteValue = getAbsoluteValue(piece, piece.color === 'w', x ,y);
    return piece.color === 'w' ? absoluteValue : -absoluteValue;
}

function evaluateBoard(game) {
    let totalEvaluation = 0;
    const board = game.board();
    for (let i = 0; i < 8; i++) {
        for (let j = 0; j < 8; j++) {
            totalEvaluation += getPieceValue(board[i][j], j, i);
        }
    }
    return totalEvaluation;
}

function minimax(game, depth, alpha, beta, isMaximizingPlayer) {
    if (depth === 0) {
        return -evaluateBoard(game);
    }

    const newGameMoves = game.moves();

    if (isMaximizingPlayer) {
        let bestMove = -9999;
        for (let i = 0; i < newGameMoves.length; i++) {
            game.move(newGameMoves[i]);
            bestMove = Math.max(bestMove, minimax(game, depth - 1, alpha, beta, !isMaximizingPlayer));
            game.undo();
            alpha = Math.max(alpha, bestMove);
            if (beta <= alpha) {
                return bestMove;
            }
        }
        return bestMove;
    } else {
        let bestMove = 9999;
        for (let i = 0; i < newGameMoves.length; i++) {
            game.move(newGameMoves[i]);
            bestMove = Math.min(bestMove, minimax(game, depth - 1, alpha, beta, !isMaximizingPlayer));
            game.undo();
            beta = Math.min(beta, bestMove);
            if (beta <= alpha) {
                return bestMove;
            }
        }
        return bestMove;
    }
}

export function calculateBestMove(game) {
    const newGameMoves = game.moves();
    if (newGameMoves.length === 0) return null;

    let bestMove = null;
    let bestValue = -9999;

    // Basic interactivity - if we are black, we want to minimize (since positive is white advantage)
    // BUT the evaluation function above returns + for White advantage.
    // If AI is Black, it should seek the LOWEST score.
    // If AI is White, it should seek the HIGHEST score.

    // Checking turn
    const isWhiteTurn = game.turn() === 'w';

    if (isWhiteTurn) {
        bestValue = -9999;
    } else {
        bestValue = 9999;
    }

    for (let i = 0; i < newGameMoves.length; i++) {
        game.move(newGameMoves[i]);
        // We look 2 moves ahead (depth 3)
        const boardValue = minimax(game, 2, -10000, 10000, !isWhiteTurn);
        game.undo();

        if (isWhiteTurn) {
            if (boardValue >= bestValue) {
                bestValue = boardValue;
                bestMove = newGameMoves[i];
            }
        } else {
            if (boardValue <= bestValue) {
                bestValue = boardValue;
                bestMove = newGameMoves[i];
            }
        }
    }
    return bestMove;
}
